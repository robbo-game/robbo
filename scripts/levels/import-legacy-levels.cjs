const fs = require('node:fs');
const path = require('node:path');
const { parseCampaign } = require('./campaign-parser.cjs');
const manifest = JSON.parse(fs.readFileSync('resources/levels/packs.json', 'utf8'));

const wallSymbols = new Set('s-OoSpPQq+');

// The historical map files are kept byte-for-byte as archival sources. These
// walls isolate a required pickup in both variants. Apply the smallest
// correction to the playable copy only.
function applyPlayableCorrections(pack) {
  for (const [number, x, y] of [[13, 11, 13], [15, 5, 22], [36, 13, 29]]) {
    const level = pack.levels[number - 1];
    if (!level || level.number !== number || level.rows[y]?.[x] !== '+') throw Error(`Unexpected planet ${number} layout in pack ${pack.id}`);
    const rows = [...level.rows];
    rows[y] = `${rows[y].slice(0, x)}.${rows[y].slice(x + 1)}`;
    pack.levels[number - 1] = { ...level, rows };
  }
}

/** Reject a map where walls permanently isolate a required pickup. Dynamic
 * objects are intentionally treated as passable: this audit catches geometry
 * errors without rejecting puzzles that require a push, shot, or bomb. */
function verifyCriticalPickupAccess(pack) {
  for (const level of pack.levels) {
    let start;
    const mirrors = [];
    for (let y = 0; y < level.height; y++) for (let x = 0; x < level.width; x++) {
      const symbol = level.rows[y][x];
      if (symbol === 'R') start = [x, y];
      if (symbol === '&') { const [group = 0] = level.options[`${x},${y}`] || []; mirrors.push([x, y, group]); }
    }
    const point = (x, y) => `${x},${y}`;
    const reachable = new Set([point(...start)]), queue = [start];
    for (let i = 0; i < queue.length; i++) {
      const [x, y] = queue[i];
      const visit = (nextX, nextY) => {
        if (nextX < 0 || nextX >= level.width || nextY < 0 || nextY >= level.height || wallSymbols.has(level.rows[nextY][nextX]) || reachable.has(point(nextX, nextY))) return;
        reachable.add(point(nextX, nextY)); queue.push([nextX, nextY]);
      };
      for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) visit(x + dx, y + dy);
      if (level.rows[y][x] === '&') {
        const [group = 0] = level.options[`${x},${y}`] || [];
        for (const [mirrorX, mirrorY, mirrorGroup] of mirrors) if (mirrorGroup === group) for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) visit(mirrorX + dx, mirrorY + dy);
      }
    }
    for (let y = 0; y < level.height; y++) for (let x = 0; x < level.width; x++) {
      if ('T%'.includes(level.rows[y][x]) && !reachable.has(point(x, y))) throw Error(`${pack.id}:${level.number}: required pickup at ${x},${y} is isolated by walls`);
    }
  }
}
if (manifest.version !== 1 || !Array.isArray(manifest.packs) || !manifest.packs.length || manifest.packs[0].id !== manifest.defaultPack) throw Error('Invalid campaign manifest/default pack');
const ids = new Set();
const packs = [];
const diagnostics = [];
for (const config of manifest.packs) {
  if (ids.has(config.id) || typeof config.file !== 'string' || path.basename(config.file) !== config.file || !config.file.endsWith('.dat')) throw Error('Invalid or duplicate pack ID/file');
  ids.add(config.id);
  const source = path.join('resources/levels', config.file);
  const result = parseCampaign(fs.readFileSync(source, 'utf8'), config, source);
  applyPlayableCorrections(result.pack);
  verifyCriticalPickupAccess(result.pack);
  packs.push(result.pack); diagnostics.push(...result.diagnostics);
}
const output = '// Generated by npm run import:levels. Do not edit; legacy source remains unchanged.\nimport type { Pack } from "../engine/model";\nexport const packs: Pack[] = ' + JSON.stringify(packs, null, 2) + ';\n';
const report = [
  '# Map import diagnostics',
  '',
  '[Documentation index](README.md) · [Campaign import](campaign-import.md)',
  '',
  '> [!NOTE]',
  '> Generated by `npm run import:levels`. Change the report in',
  '> [`scripts/levels/import-legacy-levels.cjs`](../scripts/levels/import-legacy-levels.cjs), then regenerate it.',
  '> `npm run check:levels` verifies freshness on every build.',
  '',
  '## Historical metadata policy',
  '',
  'Both canonical packs preserve 56 maps of 16×31 tiles; pack 02 is the default.',
  'Metadata applies only when its symbol matches the board cell. The stale records',
  'below are diagnosed and ignored under the canonical packs\' explicit policy.',
  'New packs should use strict metadata. Historical count lines never truncate',
  'records, and original source files remain unchanged.',
  '',
  '## Stale records',
  '',
  'Positions are zero-based **x,y** coordinates. These are preserved source-data',
  'inconsistencies, not importer failures or edits to the playable boards.',
  '',
  '| Pack | Planet | Position (zero-based) | Stale record | Actual cell |',
  '| --- | --- | --- | --- | --- |',
  ...diagnostics.map(d => `| ${d.pack} | ${d.level} | ${d.x},${d.y} | \`${d.record}\` | \`${d.actual}\` |`),
  '',
  'Source hashes and historical recovery links are in',
  '[the canonical-source notes](../resources/levels/README.md).',
  ''
].join('\n');
for (const [file, content] of [['src/generated/packs.ts', output], ['docs/import-diagnostics.md', report]]) {
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(file, 'utf8') !== content) throw Error(`${file} is stale; run npm run import:levels`);
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
}
console.log(`Imported ${packs.reduce((n, p) => n + p.levels.length, 0)} maps; ${diagnostics.length} stale records reported.`);
